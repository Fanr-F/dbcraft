import type { QueryCell } from '../../shared/ipc-contract';

export interface XlsxPayload {
  columns: string[];
  rows: QueryCell[][];
}

function escapeXml(value: string): string {
  return value
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

/** 0 → A, 25 → Z, 26 → AA。 */
export function columnName(index: number): string {
  let value = index + 1;
  let name = '';
  while (value > 0) {
    const remainder = (value - 1) % 26;
    name = String.fromCharCode(65 + remainder) + name;
    value = Math.floor((value - 1) / 26);
  }
  return name;
}

function cellXml(ref: string, value: QueryCell): string {
  if (value === null || value === undefined) return '';
  if (typeof value === 'number' && Number.isFinite(value)) {
    return `<c r="${ref}"><v>${value}</v></c>`;
  }
  if (typeof value === 'boolean') {
    return `<c r="${ref}" t="b"><v>${value ? 1 : 0}</v></c>`;
  }
  const text = escapeXml(String(value).slice(0, 32_767));
  return `<c r="${ref}" t="inlineStr"><is><t xml:space="preserve">${text}</t></is></c>`;
}

function sheetXml(payload: XlsxPayload): string {
  const rows: string[] = [];

  const headerCells = payload.columns
    .map((column, index) => cellXml(`${columnName(index)}1`, column))
    .join('');
  rows.push(`<row r="1">${headerCells}</row>`);

  payload.rows.forEach((row, rowIndex) => {
    const cells = payload.columns
      .map((_, columnIndex) =>
        cellXml(`${columnName(columnIndex)}${rowIndex + 2}`, row[columnIndex] ?? null),
      )
      .join('');
    rows.push(`<row r="${rowIndex + 2}">${cells}</row>`);
  });

  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>${rows.join(
    '',
  )}</sheetData></worksheet>`;
}

